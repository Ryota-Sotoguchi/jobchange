/** 入力中の区切りタグを無害化し、データ境界を破れないようにする */
function neutralizeTags(text: string): string {
  return text.replace(/<\s*(\/?)\s*(job_description|candidate_experience)\s*>/gi, "＜$1$2＞");
}

export function buildUserMessage(jobDescription: string, candidateExperience: string): string {
  return `以下の求人票と職務経歴を分析してください。

<job_description>
${neutralizeTags(jobDescription)}
</job_description>

<candidate_experience>
${neutralizeTags(candidateExperience)}
</candidate_experience>`;
}
